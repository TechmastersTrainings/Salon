# Database configuration
def get_database_config():
    database_url = os.getenv('DATABASE_URL')
    if database_url:
        import dj_database_url
        return dj_database_url.config(
            default=database_url,
            conn_max_age=600,
            conn_health_checks=True,
            ssl_require=True
        )

    import socket
    db_engine = os.getenv('DB_ENGINE', '').lower()
    use_sqlite = os.getenv('USE_SQLITE', '').lower() in ('true', '1') or db_engine == 'sqlite'
    
    if use_sqlite:
        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    
    # Try connecting to MySQL host and port
    mysql_host = os.getenv('DB_HOST', '127.0.0.1')
    mysql_port = int(os.getenv('DB_PORT', '3306'))
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.settimeout(0.6)
        sock.connect((mysql_host, mysql_port))
        sock.close()
        return {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.getenv('DB_NAME', 'salon_booking_db'),
            "USER": os.getenv('DB_USER', 'root'),
            "PASSWORD": os.getenv('DB_PASSWORD', 'root'),
            "HOST": mysql_host,
            "PORT": str(mysql_port),
            "OPTIONS": {
                "init_command": "SET sql_mode='STRICT_TRANS_TABLES'",
                "charset": "utf8mb4",
            },
            "CONN_MAX_AGE": 60,
        }
    except Exception:
        # Fallback to local SQLite when MySQL is unreachable
        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }

